export function resolveLanguage(
  preference: LanguagePreference,
  systemLanguage = typeof navigator === "undefined" ? "en" : navigator.language,
): UiLanguage {
  if (preference !== "system") return preference;
  if (/^(?:zh-TW|zh-HK|zh-MO|zh-Hant)(?:$|-)/i.test(systemLanguage)) return "zh-TW";
  if (/^(?:zh-CN|zh-SG|zh-Hans)(?:$|-)/i.test(systemLanguage) || /^zh$/i.test(systemLanguage)) {
    return "zh-CN";
  }
  if (/^ja(?:$|-)/i.test(systemLanguage)) return "ja";
  if (/^de(?:$|-)/i.test(systemLanguage)) return "de";
  return "en";
}

export function t(
  language: UiLanguage,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  const template = DICTIONARIES[language][key];
  return template.replace(/\{\{(\w+)\}\}/g, (_match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : `{{${name}}}`,
  );
}

export function targetText(language: UiLanguage, targetId: TargetId): { label: string; description: string } {
  return TARGET_TEXT[language][targetId];
}
